def _rows(cases, prefix, set_name):
    rows = []
    for i, (category, expected, entity, pronoun, reason, turns) in enumerate(cases, start=1):
        row = {
            "id": f"{prefix}-{i:03d}", "set": set_name, "category": category,
            "turns": turns, "expected": expected, "entity": entity,
            "pronoun": pronoun, "author": AUTHOR, "date": DATE,
            "method": M_BIND if expected == "BIND" else M_REFUSE,
        }
        if expected == "REFUSE":
            row["refuse_reason"] = reason
        rows.append(row)
    return rows


def build():
    return _rows(C_CASES, "c", "mixed"), _rows(E_CASES, "e", "paraphrase")


def write(out_dir: Path) -> None:
    mixed, para = build()
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "mixed.jsonl").write_text(
        "\n".join(json.dumps(r, ensure_ascii=False) for r in mixed) + "\n", encoding="utf-8")
    (out_dir / "paraphrase.jsonl").write_text(
        "\n".join(json.dumps(r, ensure_ascii=False) for r in para) + "\n", encoding="utf-8")
    print("mixed", len(mixed), "paraphrase", len(para))


