def write(out_dir: Path) -> None:
    rows = []
    for i, (category, expected, entity, pronoun, reason, turns) in enumerate(CASES, start=1):
        row = {
            "id": f"d-{i:03d}", "set": "hidden", "category": category,
            "turns": turns, "expected": expected, "entity": entity,
            "pronoun": pronoun, "author": AUTHOR, "date": DATE,
            "method": M_BIND if expected == "BIND" else M_REFUSE,
        }
        if expected == "REFUSE":
            row["refuse_reason"] = reason
        rows.append(row)
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "hidden.jsonl").write_text(
        "\n".join(json.dumps(r, ensure_ascii=False) for r in rows) + "\n", encoding="utf-8")
    print("hidden", len(rows))


