def main():
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, "..", "rasm_cim_v11", "data", "intent_corpus.jsonl")
    counts = {"train": 0, "dev": 0, "test": 0}
    ids = 0
    with open(out, "w", encoding="utf-8") as fh:
        for family, intent, split, texts in FAMILIES:
            for t in texts:
                ids += 1
                rec = {"id": f"v11_{split[:2]}_{ids:04d}", "text": t,
                       "intent": intent, "template": family, "split": split,
                       "source": "handwritten-2026-11-26",
                       "schema": "rasm-cim-corpus/0"}
                fh.write(json.dumps(rec, ensure_ascii=False) + "\n")
                counts[split] += 1
    print("wrote", out, counts, "total", ids)


if __name__ == "__main__":
    main()
